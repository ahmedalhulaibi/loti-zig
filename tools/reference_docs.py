#!/usr/bin/env python3
"""Render exact SDK/helper declarations for the native reference chapters."""

import argparse
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent.parent
GROUPS = {
    "setup_teardown": {
        "io_uring_queue_init", "io_uring_queue_init_params", "io_uring_queue_exit",
        "io_uring_queue_mmap", "io_uring_ring_dontfork",
    },
    "supported_caps": {
        "io_uring_get_probe", "io_uring_get_probe_ring", "io_uring_register_probe",
    },
    "completion": {
        "io_uring_wait_cqe", "io_uring_wait_cqe_nr", "io_uring_wait_cqes",
        "io_uring_wait_cqe_timeout", "io_uring_peek_cqe", "io_uring_peek_batch_cqe",
        "io_uring_cq_ready", "io_uring_cqe_seen", "io_uring_cq_advance",
    },
    "advanced_usage": {
        "io_uring_register_buffers", "io_uring_unregister_buffers",
        "io_uring_register_files", "io_uring_register_files_update",
        "io_uring_unregister_files", "io_uring_register_eventfd",
        "io_uring_register_eventfd_async", "io_uring_unregister_eventfd",
        "io_uring_register_personality", "io_uring_unregister_personality",
    },
}


def code(text):
    return ".. code-block:: zig\n\n" + "".join(
        "   " + line + "\n" if line else "\n" for line in text.splitlines()
    ) + "\n"


def declaration(text, name, fields_only=False):
    start = text.index("pub const " + name + " = extern struct {")
    end = text.index("\n};", start) + 3
    value = text[start:end]
    if fields_only:
        value = value[:value.index("\n    pub fn")].rstrip() + "\n};"
    return value


def generate():
    mapping = json.loads((ROOT / "conversion/reference-map.json").read_text())
    if subprocess.check_output(["zig", "version"], text=True).strip() != "0.17.0":
        raise ValueError("Required Zig 0.17.0")
    env = subprocess.check_output(["zig", "env"], text=True)
    match = re.search(r'\.std_dir = "([^"]+)"', env)
    if match is None:
        raise ValueError("Zig environment did not report std_dir")
    stdlib = Path(match[1])
    native = (stdlib / "os/linux.zig").read_text()
    sqe = (stdlib / "os/linux/io_uring_sqe.zig").read_text()
    outputs = {}
    signatures = [entry for entry in mapping["entries"] if "zig_signature" in entry]
    groups = dict(GROUPS)
    groups["submission"] = {
        entry["original"] for entry in signatures
        if entry["original"].startswith("io_uring_prep_")
    } | {"io_uring_get_sqe", "io_uring_submit", "io_uring_submit_and_wait", "io_uring_sq_ready"}
    for group, originals in groups.items():
        selected = {entry["zig"]: entry for entry in signatures if entry["original"] in originals}
        covered = {entry["original"] for entry in signatures if entry["original"] in originals}
        if covered != originals:
            raise ValueError(f"Missing declarations for {sorted(originals - covered)}")
        content = ".. Generated by tools/reference_docs.py; do not edit.\n\n"
        for name, entry in sorted(selected.items()):
            content += f".. rubric:: {name}\n\n" + code(entry["zig_signature"])
        outputs[f"ref-zig/_api/{group}.inc"] = content
    for name in ["io_uring_setup", "io_uring_enter", "io_uring_register"]:
        entry = next(entry for entry in signatures if entry["original"] == name)
        outputs[f"ref-iouring/_api/{name}.inc"] = code(entry["zig_signature"])
    outputs["ref-zig/_api/sqe.inc"] = code(declaration(sqe, "io_uring_sqe", fields_only=True))
    outputs["ref-zig/_api/cqe.inc"] = code(declaration(native, "io_uring_cqe"))
    outputs["ref-zig/_api/probe_types.inc"] = code(declaration(native, "io_uring_probe")) + code(declaration(native, "io_uring_probe_op"))
    outputs["ref-iouring/_api/params.inc"] = code(declaration(native, "io_uring_params"))
    outputs["ref-iouring/_api/offsets.inc"] = code(declaration(native, "io_sqring_offsets")) + code(declaration(native, "io_cqring_offsets"))
    return {relative: content.rstrip() + "\n" for relative, content in outputs.items()}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = generate()
    for relative, content in outputs.items():
        path = ROOT / relative
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit(f"Stale declaration include: {relative}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print(f"{len(outputs)} native declaration includes; Zig 0.17.0")


if __name__ == "__main__":
    main()
